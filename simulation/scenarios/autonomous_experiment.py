"""Deterministic autonomous-experiment scenario for UFCPS.

The scenario gives a research carrier an unresolved difference and a bounded
observation space. The carrier must generate a research question, hypothesis,
prediction, and method from the difference rather than receiving a predefined
experiment from the runtime.

The generated experiment is deliberately simple and deterministic so that
the architectural behavior can be inspected without depending on an external
scientific environment.
"""

from __future__ import annotations

from dataclasses import dataclass
from typing import Any

from ..core import (
    CapabilityProfile,
    Carrier,
    ExecutionResult,
    Operation,
    ProceduralState,
    RuntimeConfig,
    UFCPSRuntime,
)


@dataclass(frozen=True)
class AutonomousExperimentPlan:
    """Experiment plan generated by the research carrier."""

    question: str
    hypothesis: str
    prediction: str
    method: list[str]


@dataclass(frozen=True)
class AutonomousExperimentResult:
    """Serializable result of one autonomous research run."""

    process_id: str
    unit_id: str
    carrier_id: str
    plan: AutonomousExperimentPlan
    observations: tuple[str, ...]
    result: str
    result_class: str
    uncertainty: str
    unresolved_difference: str
    next_question: str
    state_reference: str
    continuation_ready: bool
    process_terminated: bool
    continuity_valid: bool
    metrics: dict[str, Any]
    event_log: list[dict[str, Any]]

    def to_dict(self) -> dict[str, Any]:
        """Return a JSON-serializable representation."""
        return {
            "process_id": self.process_id,
            "unit_id": self.unit_id,
            "carrier_id": self.carrier_id,
            "plan": {
                "question": self.plan.question,
                "hypothesis": self.plan.hypothesis,
                "prediction": self.plan.prediction,
                "method": list(self.plan.method),
            },
            "observations": list(self.observations),
            "result": self.result,
            "result_class": self.result_class,
            "uncertainty": self.uncertainty,
            "unresolved_difference": self.unresolved_difference,
            "next_question": self.next_question,
            "state_reference": self.state_reference,
            "continuation_ready": self.continuation_ready,
            "process_terminated": self.process_terminated,
            "continuity_valid": self.continuity_valid,
            "metrics": dict(self.metrics),
            "event_log": list(self.event_log),
        }


def generate_experiment(
    state: ProceduralState,
) -> AutonomousExperimentPlan:
    """
    Generate an experiment from the unresolved difference.

    The generator deliberately uses only information available in the
    procedural state. It does not receive a predefined experimental procedure.
    """
    difference = state.unresolved_difference.strip()

    if not difference:
        raise ValueError(
            "Autonomous experiment generation requires an unresolved difference."
        )

    question = (
        "Which controllable condition can be varied to distinguish the "
        f"current explanation of the unresolved difference from its nearest "
        f"alternative?"
    )

    hypothesis = (
        "The unresolved difference depends systematically on the condition "
        "that is most directly connected to the current boundary."
    )

    prediction = (
        "Changing the selected condition while holding the principal control "
        "constant will change the observable associated with the difference."
    )

    method = [
        "Establish a baseline observation with the control condition fixed.",
        "Vary one candidate condition while preserving the principal control.",
        "Repeat the observation under a second value of the candidate condition.",
        "Compare observations with the prediction without changing the raw observations."
    ]

    return AutonomousExperimentPlan(
        question=question,
        hypothesis=hypothesis,
        prediction=prediction,
        method=method,
    )


def execute_autonomous_experiment(
    state: ProceduralState,
    carrier: Carrier,
) -> ExecutionResult:
    """
    Execute the autonomously generated experimental procedure.

    The simulated environment supplies deterministic observations designed to
    produce a partial confirmation and a remaining discriminating question.
    """
    del carrier

    plan = generate_experiment(state)

    state.metadata["experiment_plan"] = {
        "question": plan.question,
        "hypothesis": plan.hypothesis,
        "prediction": plan.prediction,
        "method": list(plan.method),
    }

    observations = [
        "Baseline observable recorded under control condition C0.",
        "Observable changed after varying condition X1.",
        "Observable changed again under condition X2 while control C0 remained fixed.",
    ]

    state.metadata["observations"] = observations
    state.metadata["observation_interpretation_separated"] = True
    state.metadata["result_class"] = "partially_confirming"

    next_difference = (
        "The observed dependence is not yet distinguished from an alternative "
        "correlated factor."
    )

    return ExecutionResult(
        completed=True,
        current_state=(
            "Autonomous experiment completed with structured observations "
            "and a residual discriminating difference."
        ),
        local_result=(
            "The observed dependence is consistent with the working hypothesis "
            "under the tested conditions, but alternative explanations remain."
        ),
        difference=next_difference,
        next_operation=Operation.UNFOLD,
        metadata={
            "experiment_plan": {
                "question": plan.question,
                "hypothesis": plan.hypothesis,
                "prediction": plan.prediction,
                "method": list(plan.method),
            },
            "observations": observations,
            "result_class": "partially_confirming",
            "uncertainty": (
                "Moderate: the tested conditions do not isolate every "
                "potential confounder."
            ),
        },
    )


def run_autonomous_experiment(
    *,
    process_id: str = "autonomous-experiment-simulation",
) -> AutonomousExperimentResult:
    """Run the deterministic autonomous research scenario."""
    runtime = UFCPSRuntime(
        RuntimeConfig(
            process_id=process_id,
            max_steps=20,
            strict_state_sync=True,
        )
    )

    researcher = Carrier(
        carrier_id="researcher_A",
        carrier_type="autonomous_researcher",
        capabilities=CapabilityProfile(
            name="research",
            capabilities=frozenset(
                {
                    "question_generation",
                    "hypothesis_generation",
                    "experiment_design",
                    "observation",
                }
            ),
        ),
    )

    runtime.add_carrier(researcher)

    initial_state = ProceduralState(
        unit_id="ResearchP0",
        step_index=0,
        task=(
            "Investigate an unresolved discrepancy and determine whether a "
            "controlled experiment can distinguish its leading explanation "
            "from an alternative."
        ),
        current_state=(
            "An observable discrepancy persists under the current model."
        ),
        unresolved_difference=(
            "The observed discrepancy cannot yet be distinguished from an "
            "alternative correlated explanation."
        ),
        next_required_operation=Operation.DIFF,
        constraints=[
            "Change only one experimental condition at a time.",
            "Preserve the principal control condition.",
            "Record observations separately from interpretations.",
        ],
        boundary_conditions=[
            "The simulation provides deterministic observations.",
        ],
        continuation_relevant={
            "research_process": True,
            "experimental_autonomy": True,
        },
        metadata={
            "required_capabilities": [
                "question_generation",
                "hypothesis_generation",
                "experiment_design",
            ],
        },
    )

    initial_reference = runtime.add_state(initial_state)
    runtime.activate("researcher_A", "ResearchP0")

    state_before = runtime.get_state("ResearchP0")
    plan = generate_experiment(state_before)

    execution = runtime.execute(
        "ResearchP0",
        "researcher_A",
        execute_autonomous_experiment,
    )

    if not execution.completed:
        raise RuntimeError(
            "The deterministic autonomous experiment did not complete."
        )

    final_state = runtime.get_state("ResearchP0")

    observations_raw = final_state.metadata.get("observations", [])
    observations = tuple(
        item
        for item in observations_raw
        if isinstance(item, str)
    )

    result_class = str(
        final_state.metadata.get(
            "result_class",
            "inconclusive",
        )
    )

    uncertainty = str(
        execution.metadata.get(
            "uncertainty",
            "unknown",
        )
    )

    state_reference = runtime.preserve("ResearchP0")

    next_question = (
        "Which additional condition should be varied to distinguish the "
        "observed dependence from the principal alternative explanation?"
    )

    runtime.assert_continuity()

    return AutonomousExperimentResult(
        process_id=process_id,
        unit_id="ResearchP0",
        carrier_id="researcher_A",
        plan=plan,
        observations=observations,
        result=execution.local_result,
        result_class=result_class,
        uncertainty=uncertainty,
        unresolved_difference=final_state.unresolved_difference,
        next_question=next_question,
        state_reference=state_reference,
        continuation_ready=(
            bool(final_state.unresolved_difference)
            and bool(state_reference)
            and bool(observations)
        ),
        process_terminated=runtime.terminated,
        continuity_valid=True,
        metrics=runtime.metrics(),
        event_log=runtime.event_log(),
    )


def main() -> int:
    """Run the scenario and emit JSON."""
    import json

    result = run_autonomous_experiment()
    print(json.dumps(result.to_dict(), ensure_ascii=False, indent=2))

    if not result.continuity_valid:
        return 1

    if result.process_terminated:
        return 1

    if not result.plan.question.strip():
        return 1

    if not result.plan.hypothesis.strip():
        return 1

    if not result.plan.prediction.strip():
        return 1

    if not result.plan.method:
        return 1

    if not result.observations:
        return 1

    if result.result_class not in {
        "confirming",
        "disconfirming",
        "partially_confirming",
        "inconclusive",
        "anomalous",
        "invalid",
        "unreproducible",
    }:
        return 1

    if not result.continuation_ready:
        return 1

    return 0


if __name__ == "__main__":
    raise SystemExit(main())
